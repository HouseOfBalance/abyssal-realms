export function selectBossIdForFloor(floorNumber: number, biome?: BiomeId): BossId {
  if (biome === 'cathedral' || floorNumber === 5) return 'valkyria_rime_seraph';
  if (biome === 'observatory' || floorNumber >= 6) return 'chronos_time_architect';
  if (biome === 'void' || floorNumber === 4) return 'malakor_void_emperor';
  if (biome === 'forge' || floorNumber === 3) return 'ignis_forgemaster';
  if (biome === 'caverns' || floorNumber === 2) return 'arachne_broodmother';
  return 'bone_colossus';
}

export function selectColosseumBossPair(waveNumber: number): [BossId, BossId] {
  if (waveNumber < 8) {
    return ['bone_colossus', 'arachne_broodmother'];
  }
  if (waveNumber < 13) {
    return ['ignis_forgemaster', 'valkyria_rime_seraph'];
  }
  if (waveNumber < 18) {
    return ['the_butcher', 'malakor_void_emperor'];
  }
  return ['chronos_time_architect', 'malakor_void_emperor'];
}

export function computeScaledBossStats(
  blueprint: BossBlueprint,
  floorNumber: number,
): {
  maxHp: number;
  armor: number;
  attackDamage: number;
  xpReward: number;
} {
  const extraFloors = Math.max(0, floorNumber - 6);
  const endlessScale = extraFloors > 0 ? Math.pow(1.34, extraFloors) : 1;
  return {
    maxHp: Math.round(blueprint.baseMaxHp * endlessScale),
    armor: Math.round(blueprint.baseArmor + extraFloors * 14),
    attackDamage: Math.round(blueprint.baseAttackDamage * (1 + extraFloors * 0.24)),
    xpReward: Math.round(blueprint.xpReward * (1 + extraFloors * 0.35)),
  };
}

export function computeColosseumBossStats(
  blueprint: BossBlueprint,
  waveNumber: number,
): {
  maxHp: number;
  armor: number;
  attackDamage: number;
  xpReward: number;
} {
  // Normalize twin-boss stats cleanly to waveNumber so Wave 5..20+ feel epic & fair as a duo!
  const waveTier = Math.max(1, waveNumber);
  const targetSoloHp = 1350 + waveTier * 310 + Math.max(0, waveTier - 10) * 180;
  const duoHp = Math.round((targetSoloHp * 0.68 + blueprint.baseMaxHp * 0.22));
  const armor = Math.round(32 + waveTier * 3.4);
  const attackDamage = Math.round(28 + waveTier * 3.2);
  const xpReward = Math.round(450 + waveTier * 135);
  return {
    maxHp: duoHp,
    armor,
    attackDamage,
    xpReward,
  };
}

export function getDefaultStatusDuration(status: StatusEffectType): number {
  switch (status) {
    case 'stun':
      return 1.0;
    case 'freeze':
      return 1.25;
    case 'chill':
      return 3.2;
    case 'vulnerable':
      return 4.5;
    case 'burn':
      return 4.0;
    case 'poison':
      return 5.0;
    case 'bleed':
      return 4.5;
    default:
      return 3.0;
  }
}
